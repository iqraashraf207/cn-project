#!/usr/bin/env python3
"""Reads experiments/results/*.csv and logs. Writes docs/figures/*.png and docs/results_tables.md.
Usage (from the project root): python3 experiments/make_plots.py"""
import csv
import os
import re
import statistics
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "experiments", "results")
FIG = os.path.join(ROOT, "docs", "figures")
os.makedirs(FIG, exist_ok=True)
RTTS = [20, 100, 200]
md = ["# Results tables (generated by experiments/make_plots.py)", ""]


def read_csv(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        print("MISSING:", p)
        return []
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def read_log(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        print("MISSING:", p)
        return []
    out = []
    with open(p) as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 6:
                out.append(parts)
    return out


def mean_sd(v):
    return statistics.mean(v), (statistics.stdev(v) if len(v) > 1 else 0.0)


def table(headers, rows):
    md.append("| " + " | ".join(headers) + " |")
    md.append("|" + "|".join(["---"] * len(headers)) + "|")
    for r in rows:
        md.append("| " + " | ".join(str(x) for x in r) + " |")
    md.append("")


def save(fig, name):
    path = os.path.join(FIG, name)
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print("wrote", path)


# ---------------------------------------------------------------- page load
CASES = [("direct", "nonpersistent", "Direct, new connection per object", 42, "#c0392b"),
         ("direct", "persistent", "Direct, persistent connection", 22, "#2980b9"),
         ("proxy_empty", "persistent", "Via proxy, empty cache", 22, "#8e44ad"),
         ("proxy_warm", "persistent", "Via proxy, warm cache", None, "#27ae60")]
rows = read_csv("direct_full.csv") + read_csv("proxy_full.csv")
stats = {}
for lab, mode, name, k, col in CASES:
    for rtt in RTTS:
        rs = [r for r in rows if r["label"] == lab and r["mode"] == mode and int(r["rtt_ms"]) == rtt]
        if rs:
            t = [float(r["load_time_s"]) for r in rs]
            m, sd = mean_sd(t)
            stats[(lab, mode, rtt)] = dict(mean=m, sd=sd, n=len(t), min=min(t), max=max(t),
                                           conns=statistics.mean(int(r["connections"]) for r in rs),
                                           ok=all(r["all_ok"] == "True" for r in rs))

if stats:
    # Figure 1: grouped bars, linear and log scale
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5))
    for ax, log in zip(axes, (False, True)):
        w = 0.2
        for i, (lab, mode, name, k, col) in enumerate(CASES):
            xs, ys, es, ms_ = [], [], [], []
            for j, rtt in enumerate(RTTS):
                s = stats.get((lab, mode, rtt))
                if s:
                    xs.append(j + (i - 1.5) * w)
                    ys.append(s["mean"])
                    es.append(s["sd"])
                    ms_.append(k * rtt / 1000 if k else None)
            ax.bar(xs, ys, w, yerr=es, capsize=3, label=name, color=col)
            mx = [(x, m) for x, m in zip(xs, ms_) if m]
            if mx:
                ax.plot([x for x, _ in mx], [m for _, m in mx], "k_", markersize=14, mew=2,
                        label="Textbook model" if i == 0 else None)
        ax.set_xticks(range(len(RTTS)))
        ax.set_xticklabels([f"{r} ms" for r in RTTS])
        ax.set_xlabel("Round-trip time on the transit link")
        ax.set_ylabel("Page load time (s)" + (", log scale" if log else ""))
        ax.set_title("Page load time, 21 requests" + (" (log scale)" if log else ""))
        if log:
            ax.set_yscale("log")
        ax.grid(axis="y", alpha=0.3)
    axes[0].legend(fontsize=8)
    fig.suptitle("Mean of the runs, error bars = standard deviation, black dash = textbook model")
    save(fig, "fig1_page_load_time.png")

    # Figure 2: measured vs model (lines)
    fig, ax = plt.subplots(figsize=(8, 5.5))
    xs = [0] + RTTS
    ax.plot(xs, [0] + [42 * r / 1000 for r in RTTS], "--", color="#c0392b", label="Model: 42 RTT (non-persistent)")
    ax.plot(xs, [0] + [22 * r / 1000 for r in RTTS], "--", color="#2980b9", label="Model: 22 RTT (persistent)")
    for lab, mode, name, k, col in CASES:
        pts = [(r, stats[(lab, mode, r)]) for r in RTTS if (lab, mode, r) in stats]
        if pts:
            ax.errorbar([p[0] for p in pts], [p[1]["mean"] for p in pts], yerr=[p[1]["sd"] for p in pts],
                        marker="o", capsize=3, color=col, label="Measured: " + name)
    ax.set_xlabel("RTT (ms)")
    ax.set_ylabel("Page load time (s)")
    ax.set_title("Measured load time vs textbook RTT model")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    save(fig, "fig2_measured_vs_model.png")

    # Figure 3: TCP connections per page
    fig, ax = plt.subplots(figsize=(8, 5))
    labels, vals, cols = [], [], []
    for lab, mode, name, k, col in CASES:
        v = [stats[(lab, mode, r)]["conns"] for r in RTTS if (lab, mode, r) in stats]
        if v:
            labels.append(name.replace(", ", ",\n"))
            vals.append(statistics.mean(v))
            cols.append(col)
    ax.bar(labels, vals, color=cols)
    for i, v in enumerate(vals):
        ax.text(i, v + 0.3, f"{v:.0f}", ha="center", fontweight="bold")
    ax.set_ylabel("TCP connections per page load (client side)")
    ax.set_title("TCP connections opened by the client to load the page")
    ax.grid(axis="y", alpha=0.3)
    ax.tick_params(axis="x", labelsize=8)
    save(fig, "fig3_connections_per_page.png")

    # Tables
    md += ["## Page load time (mean of runs; model = textbook RTT count x RTT)", ""]
    trs = []
    for rtt in RTTS:
        for lab, mode, name, k, col in CASES:
            s = stats.get((lab, mode, rtt))
            if not s:
                continue
            model = k * rtt / 1000 if k else None
            diff = f"{(s['mean'] - model) / model * 100:+.1f}%" if model else "-"
            ovh = f"{(s['mean'] - model) / 21 * 1000:.1f}" if model else "-"
            trs.append([rtt, name, s["n"], f"{s['mean']:.3f}", f"{s['sd']:.3f}", f"{s['min']:.3f}-{s['max']:.3f}",
                        f"{s['conns']:.0f}", f"{model:.3f}" if model else "-", diff, ovh,
                        "yes" if s["ok"] else "NO"])
    table(["RTT (ms)", "Case", "Runs", "Mean (s)", "Std dev (s)", "Range (s)", "TCP conns", "Model (s)",
           "Diff vs model", "Extra ms per request", "All 200 OK"], trs)
    md += ["## Derived comparisons", ""]
    drs = []
    for rtt in RTTS:
        a, b = stats.get(("direct", "nonpersistent", rtt)), stats.get(("direct", "persistent", rtt))
        c, d = stats.get(("proxy_empty", "persistent", rtt)), stats.get(("proxy_warm", "persistent", rtt))
        drs.append([rtt,
                    f"{a['mean'] / b['mean']:.2f}x (model 1.91x)" if a and b else "-",
                    f"{a['mean'] - b['mean']:.2f}" if a and b else "-",
                    f"{(c['mean'] - b['mean']) / b['mean'] * 100:+.1f}%" if b and c else "-",
                    f"{b['mean'] / d['mean']:.0f}x" if b and d else "-",
                    f"{(1 - d['mean'] / b['mean']) * 100:.1f}%" if b and d else "-"])
    table(["RTT (ms)", "Non-persistent / persistent", "Seconds saved by persistence",
           "Proxy empty vs direct persistent", "Warm proxy speed-up vs direct persistent",
           "Load-time reduction (warm proxy)"], drs)

# ---------------------------------------------------------------- revisit (conditional GET)
rv = read_csv("revisit.csv")
rlog = read_log("revisit_proxy.log")
if rv and len(rlog) >= 84:
    names = ["Visit 1\nempty cache", "Visit 2\nfresh cache", "Visit 3\nstale, unchanged", "Visit 4\nstale, 5 objects changed"]
    times = [float(r["load_time_s"]) for r in rv[:4]]
    outcome = []
    for v in range(4):
        c = defaultdict(int)
        for p in rlog[v * 21:(v + 1) * 21]:
            c[p[3]] += 1
        outcome.append(", ".join(f"{n} {k}" for k, n in sorted(c.items())))
    fig, ax = plt.subplots(figsize=(10, 5.5))
    ax.bar(names, times, color=["#c0392b", "#27ae60", "#e67e22", "#8e44ad"])
    for i, (t, o) in enumerate(zip(times, outcome)):
        ax.text(i, t + max(times) * 0.02, f"{t:.2f} s\n{o.replace('REVALIDATE_', 'REVAL_')}", ha="center", fontsize=8)
    ax.set_ylim(0, max(times) * 1.3)
    ax.set_ylabel("Page load time (s), RTT 100 ms")
    ax.set_title("Repeat visits through the proxy (TTL 5 s): conditional GET at work")
    ax.grid(axis="y", alpha=0.3)
    save(fig, "fig4_repeat_visits.png")
    md += ["## Repeat visits (RTT 100 ms, TTL 5 s)", ""]
    table(["Visit", "Load time (s)", "Proxy log outcomes"],
          [[n.replace("\n", " - "), f"{t:.3f}", o] for n, t, o in zip(names, times, outcome)])
elif rv or rlog:
    print("revisit files incomplete: need 4 rows and 84 log lines")

# ---------------------------------------------------------------- cache hit ratio
hl = read_log("hitratio_proxy.log")
gets = [p for p in hl if p[1] == "GET"]
if len(gets) >= 21:
    loads = [gets[i:i + 21] for i in range(0, len(gets) - 20, 21)]
    hits = [sum(1 for p in L if p[3] in ("HIT", "REVALIDATE_304")) for L in loads]
    miss = [21 - h for h in hits]
    fig, ax = plt.subplots(figsize=(8, 5))
    xs = [f"Page load {i + 1}" for i in range(len(loads))]
    ax.bar(xs, hits, label="HIT or REVALIDATE_304", color="#27ae60")
    ax.bar(xs, miss, bottom=hits, label="MISS or REVALIDATE_200", color="#c0392b")
    for i, (h, m) in enumerate(zip(hits, miss)):
        if h:
            ax.text(i, h / 2, str(h), ha="center", va="center", color="white", fontweight="bold")
        if m:
            ax.text(i, h + m / 2, str(m), ha="center", va="center", color="white", fontweight="bold")
    ax.set_ylabel("Requests (of 21)")
    ax.set_ylim(0, 27)
    ax.set_yticks([0, 5, 10, 15, 21])
    total = (sum(1 for p in gets if p[3] in ("HIT", "REVALIDATE_304"))) / len(gets)
    ax.set_title(f"Cache outcome per page load, overall hit ratio = {total:.3f}")
    ax.legend(loc="upper center", ncol=2)
    save(fig, "fig5_cache_hit_ratio.png")
    md += ["## Cache hit ratio (5 consecutive page loads, TTL 3600 s)", ""]
    table(["Page load", "Hits", "Misses"], [[i + 1, h, m] for i, (h, m) in enumerate(zip(hits, miss))])
    md += [f"Overall: (HIT + REVALIDATE_304) / GET = {total:.3f} over {len(gets)} GET requests.", ""]

# ---------------------------------------------------------------- ApacheBench
abrows = {t: read_csv(f"ab_{t}.csv") for t in ("server", "proxy")}
if any(abrows.values()):
    fig, axes = plt.subplots(1, 2, figsize=(13, 5.5))
    md += ["## ApacheBench throughput (RTT 0, 3000 requests per run, same 10 KB object; 3 runs per case)", ""]
    trs = []
    for ax, t in zip(axes, ("server", "proxy")):
        g = defaultdict(list)
        failed = 0
        for r in abrows[t]:
            if r["requests_per_sec"] != "NA":
                g[(int(r["concurrency"]), r["keepalive"])].append(float(r["requests_per_sec"]))
            failed += int(r["failed"]) if r["failed"] != "NA" else 0
        allv = [x for v in g.values() for x in v]
        for i, ka in enumerate(("no", "yes")):
            xs, meds, lo, hi = [], [], [], []
            for j, c in enumerate((1, 10, 50)):
                v = g.get((c, ka))
                if v:
                    x = j + (i - 0.5) * 0.35
                    med = statistics.median(v)
                    xs.append(x)
                    meds.append(med)
                    lo.append(med - min(v))
                    hi.append(max(v) - med)
                    ax.scatter([x] * len(v), v, color="black", s=14, zorder=3)
                    trs.append([t, c, "yes (-k)" if ka == "yes" else "no", len(v), f"{med:.0f}",
                                f"{min(v):.0f}-{max(v):.0f}", f"{statistics.mean(v):.0f}"])
            ax.bar(xs, meds, 0.35, yerr=[lo, hi], capsize=3, label="keep-alive (-k)" if ka == "yes" else "no keep-alive",
                   color="#2980b9" if ka == "yes" else "#95a5a6")
        if allv:
            ax.set_ylim(min(allv) / 2, max(allv) * 2)
        ax.set_yscale("log")
        ax.set_xticks(range(3))
        ax.set_xticklabels(["c=1", "c=10", "c=50"])
        ax.set_title(("Origin server" if t == "server" else "Caching proxy (all cache hits)")
                     + f"  failed requests: {failed}")
        ax.set_ylabel("Requests per second (log scale)")
        ax.grid(axis="y", alpha=0.3)
        ax.legend(loc="lower right")
    fig.suptitle("ApacheBench: bar = median of 3 runs, whisker = min to max, dots = single runs. "
                 "Server and proxy were measured on the same machine.", fontsize=10)
    save(fig, "fig6_ab_throughput.png")
    table(["Target", "Concurrency", "Keep-alive", "Runs", "Median req/s", "Min-max", "Mean"],
          sorted(trs, key=lambda x: (x[0], x[1], x[2])))

# ---------------------------------------------------------------- bytes saved by 304
bs = os.path.join(ROOT, "docs", "evidence", "revisit_output.txt")
if os.path.exists(bs):
    txt = open(bs).read()
    m200 = re.search(r"Full 200: headers=(\d+) body=(\d+) total=(\d+)", txt)
    m304 = re.search(r"304:\s+headers=(\d+) body=(\d+) total=(\d+)", txt)
    msv = re.search(r"Saved per 304 = (\d+) bytes", txt)
    mtot = re.search(r"304 responses in this experiment's log = (\d+)\s+->\s+total saved = (\d+) bytes", txt)
    if m200 and m304 and msv and mtot:
        t200, t304, saved = int(m200.group(3)), int(m304.group(3)), int(msv.group(1))
        n304, total = int(mtot.group(1)), int(mtot.group(2))
        fig, ax = plt.subplots(figsize=(7, 5))
        ax.bar(["Full 200 response", "304 Not Modified"], [t200, t304], color=["#c0392b", "#27ae60"])
        for i, v in enumerate([t200, t304]):
            ax.text(i, v + 150, f"{v} B", ha="center", fontweight="bold")
        ax.set_ylabel("Bytes on the wire (headers + body)")
        ax.set_title(f"One 304 saves {saved} B; {n304} x 304 saved {total} B ({total / 1024:.0f} KiB)")
        ax.set_ylim(0, t200 * 1.15)
        ax.grid(axis="y", alpha=0.3)
        save(fig, "fig7_bytes_saved.png")
        md += ["## Bytes saved by 304 responses", ""]
        table(["Item", "Value"], [["Full 200 response (headers + body)", f"{t200} B"],
                                  ["304 response (headers only)", f"{t304} B"],
                                  ["Saved per 304", f"{saved} B"],
                                  ["304 responses in the repeat-visit experiment", n304],
                                  ["Total bytes saved", f"{total} B"]])
    else:
        print("revisit_output.txt found but the bytes-saved lines are missing")
else:
    print("MISSING: docs/evidence/revisit_output.txt (needed for the bytes-saved figure)")

with open(os.path.join(ROOT, "docs", "results_tables.md"), "w") as f:
    f.write("\n".join(md) + "\n")
print("wrote docs/results_tables.md")
